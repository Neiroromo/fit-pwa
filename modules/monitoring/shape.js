export const BODY_PATH = (() => {
  const [a, b, c] = SIDE;
  let d = `M${a[0][0]} ${a[0][1]} `;
  d += spline(a) + spline(b) + spline(c);
  d += spline(mir(rev(c))) + spline(mir(rev(b))) + spline(mir(rev(a)));
  return d + 'Z';
})();

