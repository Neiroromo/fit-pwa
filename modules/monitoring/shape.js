// Контуры схематичной мужской фигуры (вид спереди, система координат 200×432, ось симметрии x = 100).
// Пропорции — «8 голов»: подбородок 1 голова, соски 2, пупок 3, пах 4, колени ~6, стопы 8.
// Контур строится сплайном Катмулла–Рома по опорным точкам левой половины и зеркально достраивается справа.

/** Открытый сплайн Катмулла–Рома через точки → кубические кривые (начальная точка считается текущей). */
function spline(pts) {
  let d = '';
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[Math.max(0, i - 1)], p1 = pts[i], p2 = pts[i + 1], p3 = pts[Math.min(pts.length - 1, i + 2)];
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${c1[0].toFixed(1)} ${c1[1].toFixed(1)} ${c2[0].toFixed(1)} ${c2[1].toFixed(1)} ${p2[0]} ${p2[1]} `;
  }
  return d;
}

const mir = pts => pts.map(([x, y]) => [200 - x, y]);
const rev = pts => [...pts].reverse();

// Левая сторона фигуры (слева на рисунке = правая сторона человека). Углы (макушка шеи, носки, пах) — стыки сегментов.
